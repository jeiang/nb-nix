// Import writes a Nix module that declares the live state in snap, so that a
// plan against the same server shows no changes. Protected objects,
// ephemeral peers and unusable setup keys are left out.
func Import(w io.Writer, snap *Snapshot, server, version string) error {
	out := map[string]any{"server": server}
	parents := map[string]map[string]Doc{} // kind -> name -> nix attrs
	childSlugs := map[string]slugger{}     // parent kind/name/child kind -> slugs
	for _, k := range Kinds {
		slugs := newSlugger()
		for _, o := range snap.Objects[k.Name] {
			if skipImport(k, o) {
				continue
			}
			d := importView(k, o.Named)
			switch k.Name {
			case "groups":
				// Declared peers make membership exact; setup keys, users and JWT
				// sync also add members, so import leaves membership undeclared.
				delete(d, "peers")
			case "users":
				if str(d["role"]) == "owner" {
					delete(d, "role") // nb-nix cannot change the owner's role; ownership moves in the dashboard
				}
			}
			switch {
			case k.Name == "account":
				out["account"] = Doc{"settings": d["settings"]}
			case k.Singleton:
				out[k.Name] = d
			case k.Parent != "":
				parent := parents[k.Parent][o.ParentName]
				if parent == nil {
					continue
				}
				delete(d, k.ParentField)
				key := strings.TrimPrefix(k.Key(o.Named), o.ParentName+"/")
				sk := k.Parent + "\x00" + o.ParentName + "\x00" + k.Name
				if childSlugs[sk] == nil {
					childSlugs[sk] = newSlugger()
				}
				attrs(parent, k.ChildField)[childSlugs[sk].slug(key)] = d
			case k.Name == "users":
				local, _, _ := strings.Cut(str(d["email"]), "@")
				attrs(out, k.Name)[slugs.slug(local)] = d
			default:
				attrs(out, k.Name)[slugs.slug(str(d["name"]))] = d
				if parents[k.Name] == nil {
					parents[k.Name] = map[string]Doc{}
				}
				parents[k.Name][str(d["name"])] = d
			}
		}
	}
	fmt.Fprintf(w, "# Generated by `nb-nix import` from %s (NetBird %s).\n", server, version)
	fmt.Fprintln(w, "# Secret values are not exported: add *_file options for auth secrets you rotate,")
	fmt.Fprintln(w, "# and a sink to tokens before they need renewing.")
	fmt.Fprintln(w, "# Group members are not declared, so live membership is kept; add `peers` to make it exact.")
	fmt.Fprint(w, "{\n  netbird = ")
	writeNix(w, out, 1)
	fmt.Fprint(w, ";\n}\n")
	return nil
}

func attrs(parent map[string]any, key string) map[string]any {
	m, ok := parent[key].(map[string]any)
	if !ok {
		m = map[string]any{}
		parent[key] = m
	}
	return m
}

func skipImport(k *Kind, o *LiveObj) bool {
	switch k.Name {
	case "groups", "policies":
		return k.Protected(o.Raw, nil)
	case "peers":
		b, _ := o.Raw["ephemeral"].(bool)
		return b
	case "setup_keys":
		valid, _ := o.Raw["valid"].(bool)
		return !valid
	}
	return false
}

// importView drops hidden and secret fields and nulls.
func importView(k *Kind, d Doc) Doc {
	out := deepCopy(d).(map[string]any)
	for _, h := range k.Hidden {
		out = removePath(out, h)
	}
	for _, s := range k.Secrets {
		out = stripSecret(out, s)
	}
	return dropNulls(out).(map[string]any)
}

func removePath(d Doc, path string) Doc {
	container, key := "", path
	if i := strings.LastIndex(path, "."); i >= 0 {
		container, key = path[:i], path[i+1:]
	}
	if container == "" {
		delete(d, key)
		return d
	}
	r, _ := walkObjects(d, parsePath(container), func(m map[string]any) { delete(m, key) })
	out, _ := r.(map[string]any)
	return out
}

func dropNulls(v any) any {
	switch t := v.(type) {
	case map[string]any:
		out := map[string]any{}
		for k, e := range t {
			if e != nil {
				out[k] = dropNulls(e)
			}
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, e := range t {
			out[i] = dropNulls(e)
		}
		return out
	}
	return v
}

var nonSlug = regexp.MustCompile(`[^a-z0-9]+`)

func slug(s string) string {
	s = strings.Trim(nonSlug.ReplaceAllString(strings.ToLower(s), "-"), "-")
	if s == "" {
		return "x"
	}
	return s
}

type slugger map[string]bool

func newSlugger() slugger { return slugger{} }

func (s slugger) slug(name string) string {
	base := slug(name)
	out := base
	for i := 2; s[out]; i++ {
		out = fmt.Sprintf("%s-%d", base, i)
	}
	s[out] = true
	return out
}

var nixIdent = regexp.MustCompile(`^[a-zA-Z_][a-zA-Z0-9_'-]*$`)

var nixKeywords = map[string]bool{"if": true, "then": true, "else": true, "assert": true, "with": true,
	"let": true, "in": true, "rec": true, "inherit": true, "or": true}

func nixKey(k string) string {
	if nixIdent.MatchString(k) && !nixKeywords[k] {
		return k
	}
	return nixString(k)
}

func nixString(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "${", `\${`, "\n", `\n`, "\r", `\r`, "\t", `\t`)
	return `"` + r.Replace(s) + `"`
}

func writeNix(w io.Writer, v any, depth int) {
	ind := strings.Repeat("  ", depth)
	switch t := v.(type) {
	case map[string]any:
		if len(t) == 0 {
			fmt.Fprint(w, "{}")
			return
		}
		keys := make([]string, 0, len(t))
		for k := range t {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		fmt.Fprintln(w, "{")
		for _, k := range keys {
			fmt.Fprintf(w, "%s  %s = ", ind, nixKey(k))
			writeNix(w, t[k], depth+1)
			fmt.Fprintln(w, ";")
		}
		fmt.Fprintf(w, "%s}", ind)
	case []any:
		if len(t) == 0 {
			fmt.Fprint(w, "[]")
			return
		}
		fmt.Fprintln(w, "[")
		for _, e := range t {
			fmt.Fprintf(w, "%s  ", ind)
			writeNix(w, e, depth+1)
			fmt.Fprintln(w)
		}
		fmt.Fprintf(w, "%s]", ind)
	case string:
		fmt.Fprint(w, nixString(t))
	case json.Number:
		if strings.HasPrefix(t.String(), "-") {
			fmt.Fprintf(w, "(%s)", t)
			return
		}
		fmt.Fprint(w, t.String())
	case bool:
		fmt.Fprint(w, t)
	case nil:
		fmt.Fprint(w, "null")
	default:
		b, _ := json.Marshal(t)
		fmt.Fprint(w, string(b))
	}
}
