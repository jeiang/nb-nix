// Command gen-options generates nix/options.generated.nix (Nix module option
// declarations) from the NetBird management OpenAPI spec of the pinned module.
//
//	go run ./cmd/gen-options > nix/options.generated.nix
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// roots are the request schemas the Nix module declares objects with.
var roots = []string{
	"AccountSettings", "DNSSettings", "PostureCheckUpdate", "GroupRequest", "NetworkRequest",
	"NetworkResourceRequest", "NetworkRouterRequest", "NameserverGroupRequest", "PolicyCreate",
	"CreateSetupKeyRequest", "ServiceRequest", "PeerRequest",
}

// hidden properties cannot be declared: server-managed, read-only, or set elsewhere.
var hidden = map[string]bool{
	"PolicyRuleUpdate.id":    true,
	"GroupRequest.resources": true,
}

// secrets are write-only values; the option takes a file path instead.
var secrets = map[string]bool{
	"PasswordAuthConfig.password": true,
	"PINAuthConfig.pin":           true,
	"HeaderAuthConfig.value":      true,
}

type schema = map[string]any

type gen struct {
	schemas map[string]schema
	done    map[string]bool
	queue   []string
	out     map[string]string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-options:", err)
		os.Exit(1)
	}
}

func run() error {
	path := ""
	if len(os.Args) > 1 {
		path = os.Args[1]
	} else {
		dir, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/netbirdio/netbird").Output()
		if err != nil {
			return fmt.Errorf("locate netbird module: %w", err)
		}
		path = filepath.Join(strings.TrimSpace(string(dir)), "shared/management/http/api/openapi.yml")
	}
	version, _ := exec.Command("go", "list", "-m", "-f", "{{.Version}}", "github.com/netbirdio/netbird").Output()
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var spec struct {
		Components struct {
			Schemas map[string]schema `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(data, &spec); err != nil {
		return err
	}
	g := &gen{schemas: spec.Components.Schemas, done: map[string]bool{}, out: map[string]string{}}
	for _, r := range roots {
		g.enqueue(r)
	}
	for len(g.queue) > 0 {
		name := g.queue[0]
		g.queue = g.queue[1:]
		s, ok := g.schemas[name]
		if !ok {
			return fmt.Errorf("schema %s not found", name)
		}
		g.out[name] = g.module(name, s)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by `go run ./cmd/gen-options` from the NetBird %s management\n", strings.TrimSpace(string(version)))
	b.WriteString("# OpenAPI spec. Do not edit; regenerate after changing the NetBird version.\n")
	b.WriteString("{lib}: let\n  t = lib.types;\n")
	b.WriteString("  opt = type: description: lib.mkOption {\n    type = t.nullOr type;\n    default = null;\n    inherit description;\n  };\n")
	b.WriteString("  optDefault = type: default: description: lib.mkOption {inherit type default description;};\n")
	b.WriteString("in rec {\n")
	names := make([]string, 0, len(g.out))
	for n := range g.out {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		b.WriteString(g.out[n])
	}
	b.WriteString("}\n")
	_, err = os.Stdout.Write(b.Bytes())
	return err
}

func (g *gen) enqueue(name string) {
	if !g.done[name] {
		g.done[name] = true
		g.queue = append(g.queue, name)
	}
}

func refName(ref string) string { return strings.TrimPrefix(ref, "#/components/schemas/") }

// properties merges the properties of a schema and its allOf parts.
func (g *gen) properties(s schema) (map[string]schema, []string) {
	props := map[string]schema{}
	var owners []string
	if ref, ok := s["$ref"].(string); ok {
		return g.properties(g.schemas[refName(ref)])
	}
	if all, ok := s["allOf"].([]any); ok {
		for _, part := range all {
			ps, _ := part.(schema)
			sub, o := g.properties(ps)
			for k, v := range sub {
				props[k] = v
			}
			owners = append(owners, o...)
			if ref, ok := ps["$ref"].(string); ok {
				owners = append(owners, refName(ref))
			}
		}
	}
	if p, ok := s["properties"].(schema); ok {
		for k, v := range p {
			vs, _ := v.(schema)
			props[k] = vs
		}
	}
	return props, owners
}

func (g *gen) module(name string, s schema) string {
	props, owners := g.properties(s)
	owners = append(owners, name)
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	fmt.Fprintf(&b, "  %s = {\n    options = {\n", name)
	b.WriteString(g.options(owners, props, keys, "      "))
	b.WriteString("    };\n  };\n")
	return b.String()
}

func isOwned(owners []string, prop string, set map[string]bool) bool {
	for _, o := range owners {
		if set[o+"."+prop] {
			return true
		}
	}
	return false
}

func (g *gen) options(owners []string, props map[string]schema, keys []string, ind string) string {
	var b strings.Builder
	for _, k := range keys {
		p := props[k]
		if isOwned(owners, k, hidden) || p["readOnly"] == true {
			continue
		}
		desc := description(p)
		if isOwned(owners, k, secrets) {
			fmt.Fprintf(&b, "%s%s_file = opt t.str %s;\n", ind, k, nixString("Path to a file holding the "+k+" (write-only; read at apply)."))
			continue
		}
		typ := g.nixType(p)
		if k == "enabled" && typ == "t.bool" {
			fmt.Fprintf(&b, "%s%s = optDefault t.bool true %s;\n", ind, k, nixString(desc))
			continue
		}
		fmt.Fprintf(&b, "%s%s = opt (%s) %s;\n", ind, nixKey(k), typ, nixString(desc))
	}
	return b.String()
}

func description(p schema) string {
	d, _ := p["description"].(string)
	if d == "" {
		if ref, ok := p["$ref"].(string); ok {
			return refName(ref)
		}
	}
	return strings.TrimSpace(d)
}

func (g *gen) nixType(p schema) string {
	if ref, ok := p["$ref"].(string); ok {
		return g.refType(refName(ref))
	}
	if all, ok := p["allOf"].([]any); ok {
		if enum := g.enumValues(p); len(enum) > 0 {
			return enumType(enum)
		}
		if len(all) == 1 {
			ps, _ := all[0].(schema)
			return g.nixType(ps)
		}
		return g.inlineSubmodule(p)
	}
	if _, ok := p["oneOf"]; ok {
		return "t.anything"
	}
	if _, ok := p["anyOf"]; ok {
		return "t.anything"
	}
	if enum := g.enumValues(p); len(enum) > 0 {
		return enumType(enum)
	}
	switch p["type"] {
	case "string":
		return "t.str"
	case "integer":
		return "t.int"
	case "number":
		return "t.number"
	case "boolean":
		return "t.bool"
	case "array":
		items, _ := p["items"].(schema)
		return "t.listOf (" + g.nixType(items) + ")"
	case "object", nil:
		if _, ok := p["properties"]; ok {
			return g.inlineSubmodule(p)
		}
		switch ap := p["additionalProperties"].(type) {
		case schema:
			return "t.attrsOf (" + g.nixType(ap) + ")"
		}
		return "t.attrsOf t.anything"
	}
	return "t.anything"
}

func (g *gen) refType(name string) string {
	s := g.schemas[name]
	if enum := g.enumValues(s); len(enum) > 0 {
		return enumType(enum)
	}
	props, _ := g.properties(s)
	if len(props) == 0 {
		return g.nixType(s)
	}
	g.enqueue(name)
	return "t.submodule " + name
}

func (g *gen) inlineSubmodule(p schema) string {
	props, owners := g.properties(p)
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return "t.submodule {options = {\n" + g.options(owners, props, keys, "        ") + "      };}"
}

// enumValues returns the allowed values of a string enum, following refs
// and allOf unions (as in ResourceType).
func (g *gen) enumValues(s schema) []string {
	if s == nil {
		return nil
	}
	if ref, ok := s["$ref"].(string); ok {
		return g.enumValues(g.schemas[refName(ref)])
	}
	var out []string
	if e, ok := s["enum"].([]any); ok {
		for _, v := range e {
			out = append(out, fmt.Sprint(v))
		}
	}
	if all, ok := s["allOf"].([]any); ok {
		for _, part := range all {
			ps, _ := part.(schema)
			vals := g.enumValues(ps)
			if len(vals) == 0 {
				return nil // not a pure enum union
			}
			out = append(out, vals...)
		}
	}
	return out
}

func enumType(vals []string) string {
	q := make([]string, len(vals))
	for i, v := range vals {
		q[i] = nixString(v)
	}
	return "t.enum [" + strings.Join(q, " ") + "]"
}

func nixString(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "${", `\${`, "\n", " ", "\r", "")
	return `"` + r.Replace(s) + `"`
}

func nixKey(k string) string {
	for i, c := range k {
		if !(c == '_' || c == '-' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || i > 0 && c >= '0' && c <= '9') {
			return nixString(k)
		}
	}
	return k
}
